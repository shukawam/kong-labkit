"""Opt-in dedicated local Docker fixture; never deploys to a shared Control Plane."""
import json
import os
import shutil
import subprocess
import time
import tomllib
import uuid

import pytest
import yaml
from click.testing import CliRunner

from generator.gen import main

pytestmark = [
    pytest.mark.slow,
    pytest.mark.docker,
    pytest.mark.skipif(any(shutil.which(tool) is None for tool in ("docker", "deck", "curl", "openssl")),
                       reason="docker/deck/curl/openssl required"),
    pytest.mark.skipif(not os.environ.get("KONG_LICENSE_DATA"), reason="KONG_LICENSE_DATA required"),
]

PROJECT = "c5-custom-" + uuid.uuid4().hex[:12]
FIXED_CONTAINERS = {"database", "kong-bootstrap", "kong-cp", "kong-dp"}

# Test-owned API, not an artifact generated by kong-labkit.
SERVER = """from http.server import BaseHTTPRequestHandler, HTTPServer
import json
class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        status = 201 if self.path.endswith('/created') else 200
        body = json.dumps({'path': self.path}).encode()
        self.send_response(status)
        self.send_header('Content-Type', 'application/json')
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def log_message(self, *args):
        pass
HTTPServer(('0.0.0.0', 8080), Handler).serve_forever()
"""


def run(args, cwd):
    return subprocess.run(args, cwd=cwd, text=True, capture_output=True, timeout=300,
                          env={**os.environ, "COMPOSE_PROJECT_NAME": PROJECT})


def task(out, name):
    return tomllib.loads((out / "mise.toml").read_text())["tasks"][name]["run"]


def wait_success(args, cwd, stage):
    deadline = time.monotonic() + 90
    while time.monotonic() < deadline:
        result = run(args, cwd)
        if result.returncode == 0:
            return result
        time.sleep(2)
    # Do not dump arbitrary upstream bodies, env, or raw runtime logs on failure.
    pytest.fail(f"{stage} did not succeed within 90 seconds")


@pytest.fixture(scope="module")
def external_api(tmp_path_factory):
    work = tmp_path_factory.mktemp("custom-upstream")
    out = work / "generated"
    source = work / "input.yaml"
    api = "c5-fixture-" + uuid.uuid4().hex[:12]
    data = {"customer": "custom-smoke", "gateway": "api-gateway",
            "control_plane": "self-managed", "observability": {"backend": "none"},
            "upstream": {"url": f"http://{api}:8080/v1", "route_path": "/api",
                         "smoke": {"path": "/api/health"}}}
    source.write_text(yaml.safe_dump(data))
    result = CliRunner().invoke(main, [str(source), "-o", str(out)])
    assert result.exit_code == 0, "generation failed"
    server = work / "server.py"
    server.write_text(SERVER)
    existing = run(["docker", "ps", "-a", "--format", "{{.Names}}"], work)
    assert existing.returncode == 0, "Docker container preflight failed"
    if FIXED_CONTAINERS.intersection(existing.stdout.splitlines()):
        pytest.skip("fixed Kong lab container names are already in use; no changes made")
    try:
        assert run(["/bin/bash", "-c", task(out, "setup")], out).returncode == 0, "setup failed"
        inspected = run(["docker", "inspect", "kong-dp", "--format",
                         "{{json .NetworkSettings.Networks}}"], out)
        assert inspected.returncode == 0, "DP network inspection failed"
        network = PROJECT + "_kong-network"
        assert network in json.loads(inspected.stdout), "unique project network missing"
        started = run(["docker", "run", "-d", "--name", api, "--network", network,
                       "--network-alias", api, "--label", "kong-labkit.c5-owner=" + PROJECT, "--mount", f"type=bind,src={server},dst=/server.py,readonly",
                       "python:3.14-alpine", "python", "/server.py"], out)
        assert started.returncode == 0, "test-owned external API failed to start"
        wait_success(["/bin/bash", "-c", task(out, "smoke")], out, "initial custom smoke")
        yield out, source, data, api
    finally:
        # Only resources created by this fixture. No prune or unrelated cleanup.
        owner = run(["docker", "inspect", api, "--format",
                     '{{index .Config.Labels "kong-labkit.c5-owner"}}'], work)
        if owner.returncode == 0 and owner.stdout.strip() == PROJECT:
            run(["docker", "rm", "-f", api], work)
        # Compose cleanup is scoped to our unique project label, including partial setup.
        run(["docker", "compose", "down", "-v"], out)


@pytest.mark.parametrize("base,route,path,strip,expected", [
    ("/v1", "/api", "/api/products", True, "/v1/products"),
    ("/v1/", "/api", "/api/products", False, "/v1/api/products"),
    ("", "/products", "/products", False, "/products"),
    ("/", "/", "/products", True, "/products"),
    ("/v1", "/", "/products", False, "/v1/products"),
])
def test_custom_base_route_and_strip_reach_external_api(external_api, base, route, path, strip, expected):
    out, source, data, api = external_api
    data["upstream"] = {"url": f"http://{api}:8080{base}", "route_path": route,
                        "strip_path": strip, "smoke": {"path": path}}
    source.write_text(yaml.safe_dump(data))
    generated = CliRunner().invoke(main, [str(source), "-o", str(out), "--force"])
    assert generated.exit_code == 0, "regeneration failed"
    for _ in range(2):
        assert run(["/bin/bash", "-c", task(out, "sync")], out).returncode == 0, "sync failed"
    # Match body too: a generic 200 from the wrong API/path is insufficient.
    deadline = time.monotonic() + 60
    while time.monotonic() < deadline:
        result = run(["curl", "--silent", "--max-time", "5", f"http://localhost:8000{path}"], out)
        try:
            matched = result.returncode == 0 and json.loads(result.stdout) == {"path": expected}
        except json.JSONDecodeError:
            matched = False
        if matched:
            break
        time.sleep(2)
    else:
        pytest.fail("proxy did not reach the expected external API path")
    assert run(["/bin/bash", "-c", task(out, "smoke")], out).returncode == 0, "generated smoke failed"
    direct = run(["docker", "run", "--rm", "--network", "container:kong-dp",
                  "python:3.14-alpine", "python", "-c",
                  "import urllib.request,sys;sys.stdout.write(urllib.request.urlopen(" +
                  repr(f"http://{api}:8080" + expected) + ").read().decode())"], out)
    assert direct.returncode == 0 and json.loads(direct.stdout) == {"path": expected}


def test_generated_smoke_detects_stopped_external_api(external_api):
    out, _, _, api = external_api
    assert run(["docker", "stop", api], out).returncode == 0, "fixture stop failed"
    try:
        result = run(["/bin/bash", "-c", task(out, "smoke")], out)
        assert result.returncode != 0
        assert "smoke: OK" not in result.stdout
    finally:
        assert run(["docker", "start", api], out).returncode == 0, "fixture restart failed"


def test_generated_smoke_requires_exact_live_status(external_api):
    out, source, data, api = external_api
    data["upstream"] = {"url": f"http://{api}:8080/v1", "route_path": "/api",
                        "smoke": {"path": "/api/created", "expected_status": 201}}
    source.write_text(yaml.safe_dump(data))
    assert CliRunner().invoke(main, [str(source), "-o", str(out), "--force"]).exit_code == 0
    assert run(["/bin/bash", "-c", task(out, "sync")], out).returncode == 0, "sync failed"
    wait_success(["/bin/bash", "-c", task(out, "smoke")], out, "HTTP 201 custom smoke")
    data["upstream"]["smoke"]["expected_status"] = 200
    source.write_text(yaml.safe_dump(data))
    assert CliRunner().invoke(main, [str(source), "-o", str(out), "--force"]).exit_code == 0
    result = run(["/bin/bash", "-c", task(out, "smoke")], out)
    assert result.returncode != 0 and "smoke: OK" not in result.stdout
